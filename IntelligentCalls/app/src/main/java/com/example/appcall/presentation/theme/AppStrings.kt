fun getAppStrings(languageCode: String): TranslationStrings {
    return when (languageCode.lowercase(Locale.ROOT)) {
        "fr" -> FrenchStrings
        "ar" -> ArabicStrings
        "es" -> SpanishStrings
        "de" -> GermanStrings
        "zh" -> ChineseStrings
        "ja" -> JapaneseStrings
        "auto" -> {
            val systemLang = Locale.getDefault().language.lowercase(Locale.ROOT)
            getAppStrings(systemLang)
        }
        else -> EnglishStrings
    }
}

fun getAppLocale(languageCode: String): Locale {
    return when (languageCode.lowercase(Locale.ROOT)) {
        "fr" -> Locale.FRENCH
        "ar" -> Locale("ar")
        "es" -> Locale("es")
        "de" -> Locale.GERMAN
        "zh" -> Locale.CHINESE
        "ja" -> Locale.JAPANESE
        "auto" -> Locale.getDefault()
        else -> Locale.ENGLISH
    }
}
